"""Referee L011: write nauty.h, gtools.h, naututil.h from nauty's *-h.in templates by plain @var@ substitution (the
downloaded configure script is NOT run).  Values for x86-64 Linux + gcc.  Usage: python3 -I mkheaders.py NAUTY_SRC_DIR OUT_DIR"""
import os, re, sys
src, dst = sys.argv[1], sys.argv[2]
one = ['header_unistd_h', 'header_sys_types_h', 'header_stddef_h', 'header_stdlib_h', 'header_string_h', 'header_limits_h',
       'header_stdint_h', 'header_errno_h', 'header_sys_wait_h', 'header_signal_h', 'malloc_dec', 'has_math_inf',
       'have_flockfile', 'stdio_nolock', 'tls_supported', 'have_ansicontrols', 'flex_array_ok', 'have_clz', 'have_clzl',
       'have_clzll', 'have_popcnt', 'have_popcntl', 'have_popcntll', 'have_perror', 'have_pipe', 'have_wait', 'have_popen',
       'popen_dec', 'ftell_dec', 'fdopen_dec', 'sort_newparams_ok', 'sort_size_ok', 'have_pid_t', 'putenv_dec', 'setenv_dec',
       'have_putenv', 'have_setenv', 'have_fork', 'have_fseeko', 'have_sigaction', 'have_sigprocmask', 'have_gunzip',
       'have_isatty', 'have_times', 'have_time', 'have_getrusage', 'have_gettimeofday', 'have_clock_gettime', 'have_clock']
zero = ['default_wordsize', 'have_hwlzcnt', 'have_hwpopcnt', 'have_mmpop32', 'have_mmpop64', 'is_ARM64', 'allow_interrupt']
V = {k: '1' for k in one}
V.update({k: '0' for k in zero})
V.update(PACKAGE_VERSION='2.8.8', configure_input='referee mkheaders.py', edit_msg='generated by referee mkheaders.py',
         use_tls='', ac_cv_tls='__thread', ac_cv_noret='__attribute__((__noreturn__))', ac_cv_sys_file_offset_bits='64',
         ac_cv_sizeof_int='4', ac_cv_sizeof_long='8', ac_cv_sizeof_unsigned___int128='16', ac_cv_sizeof___uint128_t='16',
         ac_cv_sizeof_voidp='8', sort_prog='"sort"')
os.makedirs(dst, exist_ok=True)
for name in ('nauty', 'gtools', 'naututil'):
    t = open(os.path.join(src, name + '-h.in')).read()
    miss = set(re.findall(r'@([A-Za-z_0-9]+)@', t)) - set(V)
    assert not miss, (name, miss)
    open(os.path.join(dst, name + '.h'), 'w').write(re.sub(r'@([A-Za-z_0-9]+)@', lambda mo: V[mo.group(1)], t))
print('headers written to', dst)
