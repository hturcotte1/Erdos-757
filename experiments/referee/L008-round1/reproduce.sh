#!/bin/bash
# Referee L008 round 1: every computation of the review, in order (run from this directory; about 45 min single-core in total,
# dominated by the enum_conn (15,11,6) re-run (25 min), the n=10 brute force (18 min) and ext_vertex2 case B (10 min)).
# nauty 2.8.8 source: from the PyPI sdist pynauty-2.8.8.1 (pip download --no-deps pynauty), unpacked OUTSIDE this folder at $ND.
set -e
R=$(pwd); P=/home/user/Erdos-757/experiments/prover/L008; F=/home/user/Erdos-757/experiments/20261017-0300-n16-via-i11
ND=${ND:-/path/to/pynauty-2.8.8.1/src/nauty2_8_8}
mkdir -p out
# 0. programs: authors' sources copied unchanged into bin/ and recompiled; referee programs bin/bf_label.c, bin/ref_ext.c, bin/ref_filter.c
cd bin; gcc -O2 -Wall -o enum_conn enum_conn.c; gcc -O2 -o conn_dfs3 conn_dfs3.c; sed 's/SD=4/SD=6/' conn_dfs3.c > conn_dfs3s.c
cmp conn_dfs3s.c $F/conn_dfs3s.c; gcc -O2 -o conn_dfs3s conn_dfs3s.c; gcc -O2 -o ext_vertex2 ext_vertex2.c; gcc -O2 -Wall -o ext_indep2 ext_indep2.c
gcc -O2 -o filter_hits filter_hits.c; gcc -O2 -o bf_label bf_label.c; gcc -O2 -o ref_ext ref_ext.c; gcc -O2 -o ref_filter ref_filter.c; cd ..
# nauty: headers generated by sed from the .in templates (see review), then
cd nauty_build
gcc -O3 -march=native -DMAXN=WORDSIZE -DWORDSIZE=32 -DPRUNE1=tauprune -DOUTPROC=refout -DSUMMARY=refsummary -I. -I$ND -o genbg_tau $ND/genbg.c referee_hooks.c $ND/gtools.c $ND/schreier.c $ND/nauty.c $ND/nautil.c $ND/naugraph.c $ND/naurng.c
gcc -O3 -march=native -DMAXN=WORDSIZE -DWORDSIZE=32 -DPRUNE1=tauf7prune -DOUTPROC=refout -DSUMMARY=refsummary -I. -I$ND -o genbg_tauf7 $ND/genbg.c referee_hooks_f7.c $ND/gtools.c $ND/schreier.c $ND/nauty.c $ND/nautil.c $ND/naugraph.c $ND/naurng.c
gcc -O2 -DWORDSIZE=64 -DMAXN=0 -I. -I$ND -o canon3 canon3.c $ND/nauty.c $ND/nautil.c $ND/naugraph.c $ND/schreier.c $ND/naurng.c
cd ..
# 1. arithmetic: window cells, degree argument, slack cells (with and without HY), decompositions
python3 scripts/cells_check.py
# 2. brute force n<=10 and validation of genbg+prune, enum_conn, conn_dfs3 on every cell
for n in 3 4 5 6 7 8 9; do ./bin/bf_label $n 3 > out/bf_n${n}_D3.txt; ./bin/bf_label $n 100 > out/bf_n${n}_Dinf.txt; done
./bin/bf_label 10 3 > out/bf_n10_D3.txt
python3 scripts/validate_small.py 9; python3 scripts/validate_small_n10.py 10 10
# 3. enumerations: authors' programs re-run, and genbg (orderly generation) with the referee tau-prune
./bin/enum_conn 12 10 5 3 1 > out/enumconn_12_10_5_d3.txt; ./bin/conn_dfs3 12 10 5 3 0 0 > out/conndfs3_12_10_5_d3.txt
for I in 0 1; do ./bin/conn_dfs3s 12 10 5 3 0 0 2 $I > out/conndfs3s_12_part$I.txt; done
./bin/enum_conn 15 11 6 3 1 > out/enumconn_15_11_6_d3.txt
TAU0=5 nauty_build/genbg_tau -c -Z1 -d1:3 -D3:3 12 10 30:30 > out/genbg_12_10_5_d3.txt
TAU0=6 nauty_build/genbg_tau -c -Z1 -d1:3 -D3:3 15 11 33:33 > out/genbg_15_11_6_d3.txt
TAU0=6 nauty_build/genbg_tau -c -Z1 -d1:3 -D3:3 14 11 33:33 > out/genbg_14_11_6_d3.txt
TAU0=6 nauty_build/genbg_tau -c -Z1 -d1:3 -D11:3 14 11 33:33 > out/genbg_14_11_6_nodeg.txt
for c in "5 3 2" "8 4 3" "10 6 4" "11 5 4" "12 9 5" "13 7 5" "15 9 6" "15 10 6" "16 8 6"; do set -- $c; TAU0=$3 nauty_build/genbg_tau -u -c -Z1 -d1:3 -D$2:3 $1 $2 $((3*$2)):$((3*$2)); done
# class comparisons (nauty canonical forms)
cd out
../nauty_build/canon3 FOUND 12 < genbg_12_10_5_d3.txt | awk '{print $1}' | sort > genbg_12_classes.txt
../nauty_build/canon3 FOUND 12 < enumconn_12_10_5_d3.txt | awk '{print $1}' | sort -u > enumconn_12_classes.txt
../nauty_build/canon3 FOUND 12 < conndfs3_12_10_5_d3.txt | awk '{print $1}' | sort -u > conndfs3_12_classes.txt
cmp genbg_12_classes.txt enumconn_12_classes.txt; cmp genbg_12_classes.txt conndfs3_12_classes.txt
../nauty_build/canon3 FOUND 15 < genbg_15_11_6_d3.txt | awk '{print $1}' | sort > genbg_15_classes.txt
../nauty_build/canon3 FOUND 15 < enumconn_15_11_6_d3.txt | awk '{print $1}' | sort -u > prover_15_classes.txt
(zcat $F/g15_11_6_part0.txt.gz; zcat $F/g15_11_6_part1.txt.gz) | ../nauty_build/canon3 FOUND 15 | awk '{print $1}' | sort -u > falsifier_15_classes.txt
cmp genbg_15_classes.txt prover_15_classes.txt; cmp genbg_15_classes.txt falsifier_15_classes.txt
# 4. extension + filters: referee pipeline on genbg classes; authors' programs on all labelled inputs; referee filters on all hits
../bin/ref_ext A < genbg_12_10_5_d3.txt > refext_A_classes.txt; ../bin/ref_ext B < genbg_15_11_6_d3.txt > refext_B_classes.txt
../bin/ref_filter HIT 16 < refext_A_classes.txt | tail -1; ../bin/ref_filter HIT 16 < refext_B_classes.txt | tail -1
../bin/ref_filter FOUND 12 < genbg_12_10_5_d3.txt | tail -1; ../bin/ref_filter FOUND 15 < genbg_15_11_6_d3.txt | tail -1
python3 -c "
import re
w=open('inputA_all_ref.txt','w')
for l in open('enumconn_12_10_5_d3.txt'):
    if l.startswith('FOUND:'):
        es=[tuple(map(int,t.split(','))) for t in re.findall(r'\(([\d,]+)\)',l)]+[(12,13,14)]
        w.write('%d '%len(es)+' '.join('%d %d %d'%e for e in es)+'\n')"
zcat $F/G_B_conn15.txt.gz > inputB_falsifier.txt
../bin/ext_indep2 15 6 3 < inputA_all_ref.txt > hitsA_extindep2.txt; ../bin/ext_indep2 15 6 3 < inputB_falsifier.txt > hitsB_extindep2.txt
../bin/ext_vertex2 15 7 3 < inputA_all_ref.txt > hitsA_extvertex2.txt; ../bin/ext_vertex2 15 7 3 < inputB_falsifier.txt > hitsB_extvertex2.txt
../bin/ref_filter HIT 16 < hitsA_extindep2.txt | tail -1; ../bin/ref_filter HIT 16 < hitsB_extindep2.txt | tail -1
../bin/ref_filter FOUND 12 < enumconn_12_10_5_d3.txt | tail -1
for c in A B; do ../nauty_build/canon3 HIT 16 < refext_${c}_classes.txt | awk '{print $1}' | sort -u > H_${c}_classlevel.txt; ../nauty_build/canon3 HIT 16 < hits${c}_extindep2.txt | awk '{print $1}' | sort -u > H_${c}_labelled.txt; cmp H_${c}_classlevel.txt H_${c}_labelled.txt; done
sha256sum enumconn_12_10_5_d3.txt conndfs3_12_10_5_d3.txt enumconn_15_11_6_d3.txt inputA_all_ref.txt inputB_falsifier.txt hitsA_extindep2.txt hitsB_extindep2.txt hitsA_extvertex2.txt hitsB_extvertex2.txt
cd ..
# 5. controls, realizable data, gluing, witness
python3 scripts/controls.py; python3 scripts/realizable_tests.py; python3 scripts/gluing_test.py
(cd control_rerun && python3 control_sample.py && ../bin/ref_filter HIT 16 < control_sample_hits.txt | tail -1)
(cd /home/user/Erdos-757 && python3 judge/judge.py $R/witness_check/L008-C16-witness.json)
# 6. route without the component decomposition of Step 4: ALL linear (15,11,tau>=6,maxdeg<=3) 3-graphs (any connectivity,
#    isolated vertices allowed), extended and filtered (uses only Step 3 of the proof)
TAU0=6 nauty_build/genbg_tau -Z1 -d0:3 -D3:3 15 11 33:33 > out/genbg_15_11_6_d3_ALL.txt
sed -e "s/        for (int v = 0; v < 15; v++) if (deg\[v\] == 0 || deg\[v\] > 3)/        for (int v = 0; v < 15; v++) if ((mode != 'C' \&\& deg[v] == 0) || deg[v] > 3)/" bin/ref_ext.c > bin/ref_ext_c.c; gcc -O2 -o bin/ref_ext_c bin/ref_ext_c.c
(cd out && ../bin/ref_ext_c C < genbg_15_11_6_d3_ALL.txt > refext_ALL.txt && tail -n1 refext_ALL.txt && ../bin/ref_filter HIT 16 < refext_ALL.txt | tail -1)
# 7. heuristic local search for I11 / Theorem-1 violations in O+ (not a proof)
python3 scripts/hillclimb_falsify.py 7 150
