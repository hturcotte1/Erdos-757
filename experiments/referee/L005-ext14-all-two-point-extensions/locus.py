"""Referee L005, Route L: the exact deficient locus of two-point extensions, with no case analysis.

Plain Python integers; imports nothing from e757/, judge/ or the authors' experiment directory.

For a finite set A with h(A) = h and distinct reals x, y not in A, a Sidon subset of B = A u {x,y} has at most h
points in A, so h(B) <= h + 2, and h(B) = h + 2 iff S u {x,y} is Sidon for some maximum Sidon subset S of A.
Hence the deficient pairs {(x,y): h(B) <= h+1} form the locus
        D = intersection over all maximum Sidon S of  L(S),
where L(S) is the union of the lines  cx*X + cy*Y = c  given by the nontrivial relations u+v = w+z
(u,v,w,z in S u {X,Y}, multisets {u,v} != {w,z}). L(S) is generated by brute force over all pairs of multisets.
D is a finite union of whole lines and isolated points; we compute both exactly:
  * whole lines of D  = lines lying in every L(S);
  * isolated points   = for every line l of L(S_0) that is not whole: points of l that lie in L(S) for all S,
    found by intersecting l with the lines of two sets S_j with l not in L(S_j), then filtering by membership.
Every point found is re-checked against the definition (S u {x,y} not Sidon for every maximum S, sums test).
Then: whole lines are classified (X=a, Y=a with a in A, X=Y: excluded by hypothesis; any other line must contain
a 4-subset of A u {X,Y} whose difference multiset has <= 4 distinct values IDENTICALLY along the line, checked
symbolically with linear forms); isolated points with x != y, x,y not in A are tested exactly for (4,5).
A (4,5) isolated point or a whole line without such a symbolic witness would be a counterexample to L005.

The set is scaled by 12, which makes every intersection point integral (asserted).

usage:
  python3 locus.py census FILE.jsonl.gz OUT.jsonl [--classes i,j,..] [--range a:b] [--procs k]
  python3 locus.py controls FILE.jsonl.gz OUT.json --classes i,j,..   (positive controls, see controls())
"""
import sys, json, gzip, itertools, time, os, random
from math import gcd
from fractions import Fraction as Fr

SCALE = 12
NT = 4   # number of sets S_j whose intersection points seed the candidates on a line (any NT >= 1 is exact)


# ---------------------------------------------------------------- basic predicates
def is_sidon_sums(S):
    S = sorted(S)
    sums = [S[i] + S[j] for i in range(len(S)) for j in range(i, len(S))]
    return len(sums) == len(set(sums))


def ndist(q):
    return len({abs(u - v) for u, v in itertools.combinations(q, 2)})


def is45_full(P):
    return all(ndist(q) >= 5 for q in itertools.combinations(P, 4))


def max_sidon_all(P):
    """(h, list of all maximum Sidon subsets) of the sorted list P; difference definition, DFS."""
    n = len(P)
    best = [0, []]

    def rec(i, chosen, diffs):
        if len(chosen) + (n - i) < best[0]:
            return
        if i == n:
            k = len(chosen)
            if k > best[0]:
                best[0] = k
                best[1] = [tuple(chosen)]
            elif k == best[0]:
                best[1].append(tuple(chosen))
            return
        a = P[i]
        nd = [a - c for c in chosen]
        if not any(d in diffs for d in nd):
            rec(i + 1, chosen + [a], diffs | set(nd))
        rec(i + 1, chosen, diffs)

    rec(0, [], frozenset())
    return best[0], best[1]


# ---------------------------------------------------------------- relation lines
def lines_of(S):
    """dict (a,b) -> set of c: all lines aX+bY=c from nontrivial additive relations in S u {X,Y}.
    (a,b) primitive, first nonzero coordinate positive."""
    elems = [(0, 0, s) for s in S] + [(1, 0, 0), (0, 1, 0)]
    vecs = []
    for i, j in itertools.combinations_with_replacement(range(len(elems)), 2):
        u, v = elems[i], elems[j]
        vecs.append((u[0] + v[0], u[1] + v[1], u[2] + v[2]))
    assert len(set(vecs)) == len(vecs)
    L = {}
    for p, q in itertools.combinations(vecs, 2):
        cx, cy, c0 = p[0] - q[0], p[1] - q[1], p[2] - q[2]
        if cx == 0 and cy == 0:
            assert c0 != 0  # S is Sidon
            continue
        g = gcd(cx, cy)
        a, b, c = cx // g, cy // g, -c0
        assert c % g == 0
        c //= g
        if a < 0 or (a == 0 and b < 0):
            a, b, c = -a, -b, -c
        L.setdefault((a, b), set()).add(c)
    return L


def member(x, y, L):
    for (a, b), cs in L.items():
        if a * x + b * y in cs:
            return True
    return False


def tvals(line, L):
    """parameters t of the intersection points of line=(a1,b1,c1) with the lines of L (non-parallel ones).
    t = x if b1 != 0 else y."""
    a1, b1, c1 = line
    out = set()
    for (a2, b2), cs in L.items():
        det = a1 * b2 - a2 * b1
        if det == 0:
            continue
        if b1 != 0:
            nums = [c1 * b2 - c2 * b1 for c2 in cs]
        else:
            nums = [a1 * c2 - a2 * c1 for c2 in cs]
        for nm in nums:
            assert nm % det == 0, ('non-integral intersection', line, (a2, b2), det)
        out.update(nm // det for nm in nums)
    return out


def point_of(line, t):
    a1, b1, c1 = line
    if b1 != 0:
        x = t
        num = c1 - a1 * x
        assert num % b1 == 0
        return x, num // b1
    else:
        assert c1 % a1 == 0
        return c1 // a1, t


# ---------------------------------------------------------------- symbolic (4,5) along a line
def identically_failing_quad(A, line):
    """return a 4-subset (as labels) of A u {X,Y} containing X or Y with <= 4 distinct |differences|
    identically along the line, or None. Points are linear forms p + q*t."""
    a, b, c = line
    if b != 0:
        X = (Fr(0), Fr(1))
        Y = (Fr(c, b), Fr(-a, b))
    else:
        X = (Fr(c, a), Fr(0))
        Y = (Fr(0), Fr(1))
    pts = [('X', X), ('Y', Y)] + [(v, (Fr(v), Fr(0))) for v in A]

    def canon(d):
        p, q = d
        if q < 0 or (q == 0 and p < 0):
            return (-p, -q)
        return (p, q)

    for Q in itertools.combinations(pts, 4):
        labs = [l for l, _ in Q]
        if 'X' not in labs and 'Y' not in labs:
            continue
        forms = set()
        zero = False
        for (l1, u), (l2, v) in itertools.combinations(Q, 2):
            d = (u[0] - v[0], u[1] - v[1])
            if d == (0, 0):
                zero = True
            forms.add(canon(d))
        if zero:
            return ('degenerate', labs)
        if len(forms) <= 4:
            return ('quad', [str(l) for l in labs])
    return None


def b_is45(A, x, y):
    for q in itertools.combinations(A, 3):
        if ndist((x,) + q) < 5 or ndist((y,) + q) < 5:
            return False
    for q in itertools.combinations(A, 2):
        if ndist((x, y) + q) < 5:
            return False
    return True


# ---------------------------------------------------------------- the locus
def deficient_locus(A, selftest_rng=None):
    """A: sorted distinct ints (already scaled). Returns dict with h, nS, whole lines, isolated points."""
    h, allmax = max_sidon_all(A)
    Ls = [lines_of(S) for S in allmax]
    trip = [set((ab[0], ab[1], c) for ab, cs in L.items() for c in cs) for L in Ls]
    whole = set.intersection(*trip)
    Aset = set(A)
    pts = set()
    rejected = set()   # points p with p not in L(S_j) for some j: not in D (global fact, so caching is valid)
    for line in trip[0]:
        if line in whole:
            continue
        js = [j for j in range(len(Ls)) if line not in trip[j]]
        cand = None
        for j in js[:NT]:
            T = tvals(line, Ls[j])
            cand = T if cand is None else (cand & T)
        for t in cand:
            x, y = point_of(line, t)
            if x == y or x in Aset or y in Aset:
                continue
            if (x, y) in pts or (x, y) in rejected:
                continue
            if all(member(x, y, Ls[j]) for j in js):
                pts.add((x, y))
            else:
                rejected.add((x, y))
    # definition re-check of every point found (sums test, independent of lines_of)
    for (x, y) in pts:
        for S in allmax:
            assert not is_sidon_sums(list(S) + [x, y]), ('point not deficient', x, y, S)
    # self-test of the membership predicate against the definition on random and special points
    if selftest_rng is not None:
        lo, hi = A[0] - (A[-1] - A[0]), A[-1] + (A[-1] - A[0])
        probe = [(selftest_rng.randrange(lo, hi), selftest_rng.randrange(lo, hi)) for _ in range(150)]
        probe += list(pts)[:150]
        # special points: midpoints/endpoints combos (likely relation points)
        sp = []
        for p, q in itertools.combinations(A, 2):
            if (p + q) % 2 == 0:
                sp.append((p + q) // 2)
            sp.append(2 * p - q); sp.append(2 * q - p)
        for _ in range(300):
            sp_x = selftest_rng.choice(sp); sp_y = selftest_rng.choice(sp + [selftest_rng.randrange(lo, hi)])
            probe.append((sp_x, sp_y))
        for (x, y) in probe:
            if x == y or x in Aset or y in Aset:
                continue
            for S in allmax[:5] + allmax[-3:]:
                L = lines_of(S)
                assert member(x, y, L) == (not is_sidon_sums(list(S) + [x, y])), ('membership mismatch', x, y, S)
    return h, allmax, whole, pts


def analyse(A, label, rng=None):
    t0 = time.time()
    h, allmax, whole, pts = deficient_locus(A, rng)
    Aset = set(A)
    wl = {'excluded_X=a': 0, 'excluded_Y=a': 0, 'excluded_X=Y': 0, 'other_with_witness': 0, 'flagged': []}
    witness_examples = []
    for line in sorted(whole):
        a, b, c = line
        if (a, b) == (1, 0) and c in Aset:
            wl['excluded_X=a'] += 1
        elif (a, b) == (0, 1) and c in Aset:
            wl['excluded_Y=a'] += 1
        elif (a, b, c) == (1, -1, 0):
            wl['excluded_X=Y'] += 1
        else:
            w = identically_failing_quad(A, line)
            if w is None or w[0] != 'quad':
                wl['flagged'].append([line, w])
            else:
                wl['other_with_witness'] += 1
                if len(witness_examples) < 3:
                    witness_examples.append([line, w[1]])
    p45 = [(x, y) for (x, y) in sorted(pts) if b_is45(A, x, y)]
    return {'label': label, 'h': h, 'nS': len(allmax), 'n_whole': len(whole), 'whole': wl,
            'whole_witness_examples': [[list(l), q] for l, q in witness_examples],
            'n_isolated_pts': len(pts), 'n_pts_45': len(p45), 'pts_45': [list(p) for p in p45[:20]],
            'secs': round(time.time() - t0, 2)}


def load_census(path):
    out = []
    for line in gzip.open(path, 'rt'):
        if line.strip():
            out.append(json.loads(line)['set'])
    return out


def work(args):
    idx, P, seed = args
    try:
        os.nice(0)
    except Exception:
        pass
    A = sorted(SCALE * v for v in P)
    assert is45_full(A)
    rng = random.Random(seed) if seed is not None else None
    r = analyse(A, idx, rng)
    r['class'] = idx
    return r


def main_census(path, outp, classes, procs, selftest_every):
    sets = load_census(path)
    done = set()
    if os.path.exists(outp):
        for l in open(outp):
            try:
                done.add(json.loads(l)['class'])
            except Exception:
                pass
    todo = [(i, sets[i], (1000 + i) if (selftest_every and i % selftest_every == 0) else None)
            for i in classes if i not in done]
    t0 = time.time()
    with open(outp, 'a') as fo:
        if procs > 1:
            from multiprocessing import Pool
            with Pool(procs) as pool:
                for k, r in enumerate(pool.imap_unordered(work, todo, chunksize=4)):
                    fo.write(json.dumps(r) + '\n'); fo.flush()
                    if (k + 1) % 100 == 0:
                        print(k + 1, len(todo), round(time.time() - t0), flush=True)
        else:
            for k, a in enumerate(todo):
                r = work(a)
                fo.write(json.dumps(r) + '\n'); fo.flush()
                if (k + 1) % 50 == 0:
                    print(k + 1, len(todo), round(time.time() - t0), flush=True)
    print('done', len(todo), 'classes in', round(time.time() - t0), 's', flush=True)


def controls(path, outp, classes):
    """Positive controls on census sets A (h = 8):
    PC1: A' = A minus {p,q} with h(A') = 7: the pair (p,q) restores A, so h(A' u {p,q}) = 8 = h(A')+1 and (p,q) must be
         found as a (4,5) deficient point (isolated, or on a flagged whole line).
    PC2: A' = A minus {p} with h(A') = 8: the line X = p must be a whole line of D' WITHOUT a symbolic witness (flagged).
    """
    sets = load_census(path)
    res = []
    for idx in classes:
        A = sorted(SCALE * v for v in sets[idx])
        rng = random.Random(idx)
        # PC1
        pairs = list(itertools.combinations(A, 2))
        rng.shuffle(pairs)
        n1 = 0
        for (p, q) in pairs:
            Ap = [v for v in A if v not in (p, q)]
            h, _ = max_sidon_all(Ap)
            if h != 7:
                continue
            r = analyse(Ap, 'PC1', None)
            found_pt = [p, q] in r['pts_45'] or [q, p] in r['pts_45']
            # if more than 20 (4,5) points were found, pts_45 is truncated; recompute membership directly
            if not found_pt and r['n_pts_45'] > 20:
                hh, allmax, whole, pts = deficient_locus(Ap)
                found_pt = (p, q) in pts or (q, p) in pts
            # or (p,q) lies on a flagged whole line (a whole line of D' with (4,5) generic points)
            for f in r['whole']['flagged']:
                a, b, c = f[0]
                if a * p + b * q == c or a * q + b * p == c:
                    found_pt = True
            res.append({'class': idx, 'control': 'PC1', 'removed': [p, q], 'h_Aprime': h, 'found': found_pt,
                        'n_pts_45': r['n_pts_45'], 'n_flagged_whole': len(r['whole']['flagged'])})
            n1 += 1
            if n1 >= 2:
                break
        # PC2
        singles = list(A)
        rng.shuffle(singles)
        n2 = 0
        for p in singles:
            Ap = [v for v in A if v != p]
            h, _ = max_sidon_all(Ap)
            if h != 8:
                continue
            r = analyse(Ap, 'PC2', None)
            flagged = [tuple(f[0]) for f in r['whole']['flagged']]
            res.append({'class': idx, 'control': 'PC2', 'removed': [p], 'h_Aprime': h,
                        'found': (1, 0, p) in flagged and (0, 1, p) in flagged,
                        'flagged': [list(f) for f in flagged][:10], 'n_pts_45': r['n_pts_45']})
            n2 += 1
            if n2 >= 1:
                break
        print(json.dumps(res[-3:]), flush=True)
    json.dump(res, open(outp, 'w'), indent=1)
    print('controls', len(res), 'all found:', all(r['found'] for r in res))


def parse_classes(argv, n):
    if '--classes' in argv:
        return [int(v) for v in argv[argv.index('--classes') + 1].split(',')]
    if '--range' in argv:
        a, b = argv[argv.index('--range') + 1].split(':')
        return list(range(int(a), min(int(b), n)))
    return list(range(n))


if __name__ == '__main__':
    mode, path, outp = sys.argv[1], sys.argv[2], sys.argv[3]
    try:
        os.nice(15)
    except Exception:
        pass
    n = len(load_census(path))
    cl = parse_classes(sys.argv, n)
    procs = int(sys.argv[sys.argv.index('--procs') + 1]) if '--procs' in sys.argv else 1
    if mode == 'census':
        st = int(sys.argv[sys.argv.index('--selftest-every') + 1]) if '--selftest-every' in sys.argv else 0
        main_census(path, outp, cl, procs, st)
    elif mode == 'controls':
        controls(path, outp, cl)
