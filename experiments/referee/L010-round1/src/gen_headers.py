"""Generate nauty.h, gtools.h, naututil.h from nauty's *.in templates by plain substitution (instead of running the
untrusted configure script).  Values chosen for x86-64 Linux / gcc.  Usage: python3 -I gen_headers.py SRC_DIR OUT_DIR"""
import sys, re, os
src, out = sys.argv[1], sys.argv[2]
V = dict(PACKAGE_VERSION='2.8.8', configure_input='generated by referee gen_headers.py', edit_msg='generated header',
    header_unistd_h='1', header_sys_types_h='1', header_stddef_h='1', header_stdlib_h='1', header_string_h='1',
    header_limits_h='1', header_stdint_h='1', malloc_dec='1', has_math_inf='1', have_flockfile='1', stdio_nolock='1',
    default_wordsize='0', tls_supported='1', use_tls='', ac_cv_tls='__thread', ac_cv_noret='__attribute__((__noreturn__))',
    have_ansicontrols='1', flex_array_ok='1', ac_cv_sys_file_offset_bits='64', have_hwlzcnt='0', have_clz='1',
    have_clzl='1', have_clzll='1', have_hwpopcnt='0', have_popcnt='1', have_popcntl='1', have_popcntll='1',
    have_mmpop32='0', have_mmpop64='0', is_ARM64='0', ac_cv_sizeof_int='4', ac_cv_sizeof_long='8',
    ac_cv_sizeof_unsigned___int128='16', ac_cv_sizeof___uint128_t='16', ac_cv_sizeof_voidp='8',
    header_errno_h='1', have_perror='1', have_pipe='1', have_wait='1', header_sys_wait_h='1', have_popen='1',
    popen_dec='1', ftell_dec='1', fdopen_dec='1', sort_prog='"sort"', sort_newparams_ok='1', sort_size_ok='1',
    have_pid_t='1', putenv_dec='1', setenv_dec='1', have_putenv='1', have_setenv='1', have_fork='1',
    header_signal_h='1', have_fseeko='1', have_sigaction='1', have_sigprocmask='1', have_gunzip='1',
    allow_interrupt='0', have_isatty='1', have_times='1', have_time='1', have_getrusage='1', have_gettimeofday='1',
    have_clock_gettime='1', have_clock='1')
for name in ['nauty', 'gtools', 'naututil']:
    t = open(os.path.join(src, name + '-h.in')).read()
    missing = set(re.findall(r'@([A-Za-z_0-9]+)@', t)) - set(V)
    assert not missing, missing
    t = re.sub(r'@([A-Za-z_0-9]+)@', lambda mo: V[mo.group(1)], t)
    open(os.path.join(out, name + '.h'), 'w').write(t)
print('ok')
