"""Referee F7 detector, from the definition (not Lemma F): H contains F7 iff some 5 edges, after relabelling their
union (which must have 7 vertices) to 0..6 increasingly, form one of the labelled copies of F7 on {0..6}, which are
generated by applying all 5040 permutations to F7 = {012,034,056,135,246}."""
import itertools, re, sys, json
F7 = [(0,1,2),(0,3,4),(0,5,6),(1,3,5),(2,4,6)]
COPIES = set()
for p in itertools.permutations(range(7)):
    COPIES.add(frozenset(frozenset(p[v] for v in e) for e in F7))
assert len(COPIES) == 420, len(COPIES)   # 7!/|Aut F7| = 5040/12
def f7_copies(es, first_only=False):
    es = [frozenset(e) for e in es]
    found = []
    for five in itertools.combinations(range(len(es)), 5):
        U = set().union(*(es[i] for i in five))
        if len(U) != 7: continue
        rl = {v: k for k, v in enumerate(sorted(U))}
        key = frozenset(frozenset(rl[v] for v in es[i]) for i in five)
        if key in COPIES:
            found.append(five)
            if first_only: return found
    return found
def has_f7(es): return bool(f7_copies(es, True))
def is_linear(es):
    seen = set()
    for e in es:
        for p in itertools.combinations(sorted(e), 2):
            if p in seen: return False
            seen.add(p)
    return True
def parse(path, tag):
    out = []
    for l in open(path):
        if l.startswith(tag):
            out.append([tuple(sorted(map(int, t.split(',')))) for t in re.findall(r'\(([\d,]+)\)', l)])
    return out
if __name__ == '__main__':
    rep = {}
    for arg in sys.argv[1:]:
        path, tag = arg.rsplit(':', 1)
        L = parse(path, tag + ':')
        lin = sum(is_linear(es) for es in L); f = sum(has_f7(es) for es in L)
        rep[path] = dict(graphs=len(L), linear=lin, contain_F7=f, F7_free=len(L) - f)
        print(path, rep[path], flush=True)
